#!/usr/bin/env bash
# Point packages/bc250-pytorch/PKGBUILD at one build of the wheels.
#
#   rocm/update-pkgbuild.sh <build id>            SHA256SUMS from the rocm-pytorch release
#   rocm/update-pkgbuild.sh <wheelhouse dir>      SHA256SUMS + BUILD_ID from a local build
#
# Rewrites the block between the "generated" markers: build id, torch and ROCm
# versions (from the wheel names) and every wheel with its checksum. Resets
# pkgrel to 1 when the versions change. Commit the result; the nightly workflow
# then packages it because the package directory changed.
set -Eeuo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
PKGBUILD="$ROOT/packages/bc250-pytorch/PKGBUILD"
arg="${1:?usage: $0 <build id | wheelhouse dir>}"

if [[ -d "$arg" ]]; then
    sums="$(cat "$arg/SHA256SUMS")"
    id="$(cat "$arg/BUILD_ID")"
else
    id="$arg"
    sums="$(gh release download rocm-pytorch -R MastaG/linux-cachyos-bc250 \
        --pattern "$id--SHA256SUMS" --output -)"
fi
[[ "$id" =~ ^[0-9a-f]{12}$ ]] || { echo "not a build id: $id" >&2; exit 1; }

SUMS="$sums" python3 - "$PKGBUILD" "$id" <<'EOF'
import os, re, sys
path, build_id = sys.argv[1], sys.argv[2]
rows = [l.split() for l in os.environ["SUMS"].splitlines() if l.strip()]
wheels = sorted((name, digest) for digest, name in rows)
assert wheels and all(re.fullmatch(r"[0-9a-f]{64}", d) for _, d in wheels), "bad SHA256SUMS"

def version(dist):
    found = [n.split("-")[1] for n, _ in wheels if n.split("-")[0] == dist]
    assert len(found) == 1, f"expected one {dist} wheel, found {found}"
    return found[0]

torch = version("torch").split("+")[0]
rocm = version("rocm")
block = "\n".join([
    "# BEGIN generated by rocm/update-pkgbuild.sh",
    f"_build_id={build_id}",
    f"_torch={torch}",
    f"_rocm={rocm}",
    "_wheels=(",
    *[f"    '{n}'" for n, _ in wheels],
    ")",
    "_wheel_sums=(",
    *[f"    '{d}'" for _, d in wheels],
    ")",
    "# END generated by rocm/update-pkgbuild.sh",
])
text = open(path).read()
old = re.search(r"# BEGIN generated by rocm/update-pkgbuild.sh\n.*?# END generated by rocm/update-pkgbuild.sh", text, re.S)
assert old, "markers missing in PKGBUILD"
before = re.search(r"^_torch=(.*)$", old.group(0), re.M).group(1), re.search(r"^_rocm=(.*)$", old.group(0), re.M).group(1)
text = text[:old.start()] + block + text[old.end():]
if before != (torch, rocm):
    text = re.sub(r"^pkgrel=.*$", "pkgrel=1", text, count=1, flags=re.M)
open(path, "w").write(text)
print(f"PKGBUILD -> build {build_id}: torch {torch}, rocm {rocm}, {len(wheels)} wheels")
EOF
